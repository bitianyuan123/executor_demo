#!/usr/bin/env python3
"""Keep stage 4's standalone business router algorithm identical to stage 5.

The generated files are committed: stages 3/4 require only stock Folly headers.
This script is needed only when intentionally refreshing or checking the
stage-5 comparison. It does not run as part of a normal build.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def transformed(header, test):
    preamble = "// Generated by scripts/sync_business_executor.py; edit the canonical experimental source, then refresh.\n"
    h = header.replace("namespace folly::experimental {", "namespace executor_demo {\nusing folly::BlockingQueue;\nusing folly::CPUThreadPoolExecutor;\nusing folly::ThreadFactory;\nusing folly::Func;")
    h = h.replace("namespace folly::experimental", "namespace executor_demo")
    h = h.replace("AffinityExecutor", "BusinessExecutor")
    t = test.replace("#include <folly/executors/experimental/AffinityExecutor.h>", "#include <executor_demo/BusinessExecutor.h>")
    t = t.replace("namespace folly::experimental", "namespace executor_demo")
    t = t.replace("AffinityExecutor", "BusinessExecutor")
    return preamble+h, preamble+t


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--folly-dir",type=Path,default=ROOT.parent/"folly")
    p.add_argument("--check",action="store_true")
    a=p.parse_args()
    source=a.folly_dir/"folly/executors/experimental"
    header=(source/"AffinityExecutor.h").read_text()
    test=(source/"test/AffinityExecutorTest.cpp").read_text()
    h,t=transformed(header,test)
    files={ROOT/"experiments/dag/include/executor_demo/BusinessExecutor.h":h,
           ROOT/"experiments/dag/tests/business_executor_test.cpp":t}
    metadata={"canonical_header":"folly/executors/experimental/AffinityExecutor.h",
              "canonical_header_sha256":hashlib.sha256(header.encode()).hexdigest(),
              "canonical_test_sha256":hashlib.sha256(test.encode()).hexdigest(),
              "business_header_sha256":hashlib.sha256(h.encode()).hexdigest(),
              "transformation":"namespace/class/include changes only; same placement algorithm and accounting"}
    files[ROOT/"experiments/dag/business-source.json"]=json.dumps(metadata,indent=2)+"\n"
    for path,content in files.items():
        if a.check:
            if not path.exists() or path.read_text()!=content:
                raise SystemExit(f"Algorithm mirror mismatch: {path}")
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(content)
    print("business/library algorithm mirror verified" if a.check else "business router and tests refreshed")


if __name__=="__main__":main()
